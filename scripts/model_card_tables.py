"""Per-packaging-type performance of the frozen models for the model card (PLAN 10.4).

Pooled OOF predictions (seed-averaged) of each frozen model's 15 development runs, split by
packaging type: AUROC with a 95% stratified bootstrap CI (2000 resamples, seed 0) and the
error rate of the majority val-threshold decision. Writes
``results/tables/model_card_by_packaging.{csv,md}``.

Usage:
    python scripts/model_card_tables.py
"""

from __future__ import annotations

import argparse
import sys

import pandas as pd

from pharmachecked.config import REPO_ROOT
from pharmachecked.evaluation.aggregate import collect_runs, pooled_oof, to_markdown
from pharmachecked.evaluation.metrics import auroc
from pharmachecked.evaluation.stats import bootstrap_ci
from pharmachecked.utils.io import atomic_write_text

FROZEN = {  # ADR-030
    "final model (EfficientNetV2-S)": ("e05", "efficientnetv2-s", "default"),
    "E1 best (ConvNeXt-T, data v2)": ("p4ref", "convnext-tiny", "ft"),
    "E16 student (MobileNetV3-L, KD T=4)": ("e16", "mobilenetv3-large", "kd-t4"),
}


def main() -> int:
    """CLI entry point; returns a process exit code."""
    argparse.ArgumentParser(description=__doc__.splitlines()[0]).parse_args()
    rows = []
    for name, (exp, model, variant) in FROZEN.items():
        recs = [
            r
            for r in collect_runs(REPO_ROOT / "results" / "runs", exp)
            if r.model == model and r.variant == variant
        ]
        pooled = pooled_oof(recs)
        for ptype, part in pooled.groupby("packaging_type"):
            y, p = part["y_true"].to_numpy(), part["prob"].to_numpy()
            both = 0 < y.sum() < len(y)
            ci = bootstrap_ci(y, (p,), auroc) if both else None
            rows.append(
                {
                    "model": name,
                    "packaging type": ptype,
                    "images": len(part),
                    "counterfeit": int(y.sum()),
                    "AUROC (pooled OOF)": f"{ci.estimate:.3f} [{ci.low:.3f}, {ci.high:.3f}]"
                    if ci
                    else "n/a (one class)",
                    "error rate (val threshold)": round(float((part["decision"] != y).mean()), 4),
                }
            )
    table = pd.DataFrame(rows)
    out = REPO_ROOT / "results" / "tables" / "model_card_by_packaging"
    table.to_csv(out.with_suffix(".csv"), index=False, lineterminator="\n")
    atomic_write_text(
        out.with_suffix(".md"),
        "# Frozen models by packaging type (development OOF)\n\nGenerated by "
        "`scripts/model_card_tables.py`. Seed-averaged pooled OOF predictions of the 15 runs; "
        "95% stratified bootstrap CI (2000 resamples, seed 0); error = majority decision at "
        "each run's val-selected threshold.\n\n" + to_markdown(table),
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
