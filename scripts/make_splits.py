"""Create splits/v{N}.json, fill split/fold in the manifest, and write the class-balance table.

The locked test set is carved once, in v1. Later versions copy its membership unchanged
(ADR-002). An existing split file is never overwritten with different content.

Usage:
    python scripts/make_splits.py --version 1
    python scripts/make_splits.py --version 2 --manifest data/processed/manifest_v2.csv
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd
from omegaconf import OmegaConf

from pharmachecked.config import CONFIG_DIR, REPO_ROOT
from pharmachecked.data.manifest import read_manifest, write_manifest
from pharmachecked.data.splits import (
    PARTS,
    SplitSettings,
    apply_to_manifest,
    make_splits,
    save_splits,
)
from pharmachecked.utils.io import atomic_write_text
from pharmachecked.utils.logging import configure_logging, get_logger

log = get_logger("make_splits")


def balance_table(manifest: pd.DataFrame, spec: dict) -> str:
    """Markdown table of counts, counterfeit share and groups per partition."""
    label = dict(zip(manifest["image_id"], manifest["label"], strict=True))
    group = dict(zip(manifest["image_id"], manifest["group_id"], strict=True))
    pool_share = manifest["label"].mean()

    def row(name: str, ids: list[str]) -> str:
        n_cf = sum(label[i] for i in ids)
        share = n_cf / len(ids)
        return (
            f"| {name} | {len(ids)} | {len(ids) - n_cf} | {n_cf} | {100 * share:.1f} | "
            f"{100 * (share - pool_share):+.1f} | {len({group[i] for i in ids})} |"
        )

    lines = [
        f"# Split balance (splits/v{spec['version']}.json)",
        "",
        "Generated by `scripts/make_splits.py`. Counterfeit share of the whole pool: "
        f"{100 * pool_share:.1f}%. Difference = partition share minus pool share (percentage "
        "points).",
        "",
        "| Partition | Images | Authentic | Counterfeit | Counterfeit % | Difference (pp) "
        "| Groups |",
        "|---|---|---|---|---|---|---|",
        row("locked test", spec["locked_test"]),
        row("development pool", [i for f in spec["folds"] for i in f["heldout"]]),
    ]
    for f in spec["folds"]:
        for part in PARTS:
            lines.append(row(f"fold {f['fold']} {part}", f[part]))
    return "\n".join(lines) + "\n"


def main() -> int:
    """CLI entry point; returns a process exit code."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--version", type=int, required=True)
    parser.add_argument("--manifest", type=Path, default=None)
    args = parser.parse_args()
    configure_logging()
    manifest_path = (
        args.manifest or REPO_ROOT / "data" / "processed" / "manifest_v1.csv"
    ).resolve()
    out = REPO_ROOT / "splits" / f"v{args.version}.json"
    manifest = read_manifest(manifest_path)
    previous = None
    if args.version > 1:
        prev = REPO_ROOT / "splits" / f"v{args.version - 1}.json"
        previous = json.loads(prev.read_text(encoding="utf-8"))["locked_test"]
    dd = OmegaConf.load(CONFIG_DIR / "data" / "dedup.yaml")
    extra = {
        "manifest": manifest_path.relative_to(REPO_ROOT).as_posix(),
        "phash_threshold": int(dd.phash_threshold),
    }
    spec = make_splits(manifest, SplitSettings(), args.version, previous, extra)
    if out.exists():
        existing = json.loads(out.read_text(encoding="utf-8"))
        if existing != spec:
            log.error("%s exists with different content; refusing to overwrite", out)
            return 1
        log.info("%s already exists and is identical", out)
    else:
        save_splits(spec, out)
        log.info("wrote %s", out)
    write_manifest(apply_to_manifest(manifest, spec), manifest_path)
    table = (
        REPO_ROOT
        / "results"
        / "tables"
        / ("split_balance.md" if args.version == 1 else f"split_balance_v{args.version}.md")
    )
    atomic_write_text(table, balance_table(manifest, spec))
    log.info("updated %s and wrote %s", manifest_path.name, table.name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
