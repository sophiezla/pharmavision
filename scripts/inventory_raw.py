"""Read-only inventory of data/raw (PLAN step 1.1) -> results/tables/raw_inventory.md.

Reports, per source and class folder: file counts, formats, colour modes, image and file-size
distributions, unreadable files, and exact duplicates within and across sources. Nothing under
data/raw is modified.

Usage:
    python scripts/inventory_raw.py
"""

from __future__ import annotations

import hashlib
import statistics
import sys
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from pathlib import Path

from omegaconf import OmegaConf
from PIL import Image

from pharmachecked.config import CONFIG_DIR, REPO_ROOT
from pharmachecked.data.sources import RawFile, list_raw_files, load_specs
from pharmachecked.utils.io import atomic_write_text
from pharmachecked.utils.logging import configure_logging, get_logger

log = get_logger("inventory_raw")
LABEL_NAMES = {0: "authentic", 1: "counterfeit", None: "unlabelled"}


@dataclass
class FileInfo:
    """Facts about one raw file."""

    raw: RawFile
    sha256: str
    size_bytes: int
    readable: bool
    error: str = ""
    fmt: str = ""
    mode: str = ""
    width: int = 0
    height: int = 0
    transparent: bool = False  # has an alpha channel with any pixel below 255


@dataclass
class Group:
    """Accumulator for one (source, class folder) row."""

    infos: list[FileInfo] = field(default_factory=list)


def inspect(raw: RawFile) -> FileInfo:
    """Hash and decode one file without modifying it."""
    data = raw.path.read_bytes()
    info = FileInfo(raw, hashlib.sha256(data).hexdigest(), len(data), readable=False)
    try:
        with Image.open(raw.path) as im:
            info.fmt, info.mode, (info.width, info.height) = im.format or "", im.mode, im.size
            im.load()  # full decode catches truncated files
            if "A" in im.getbands() or "transparency" in im.info:
                alpha = im.convert("RGBA").getchannel("A")
                info.transparent = alpha.getextrema()[0] < 255
        info.readable = True
    except Exception as exc:  # any decode failure is reported, not raised
        info.error = f"{type(exc).__name__}: {exc}"
    return info


def _q(values: list[float]) -> str:
    """Median [min-max] of a list, or '-' when empty."""
    if not values:
        return "-"
    return f"{statistics.median(values):.0f} [{min(values):.0f}-{max(values):.0f}]"


def _counts(counter: Counter[str]) -> str:
    return ", ".join(f"{k} {v}" for k, v in sorted(counter.items()))


def render(infos: list[FileInfo], other_files: list[Path]) -> str:
    """Build the Markdown report."""
    groups: dict[tuple[str, str], list[FileInfo]] = defaultdict(list)
    for info in infos:
        groups[(info.raw.source, info.raw.class_folder)].append(info)

    lines = [
        "# Raw data inventory (PLAN 1.1)",
        "",
        "Generated by `scripts/inventory_raw.py` (read-only scan of `data/raw/`). Roles and labels",
        "come from `configs/data/sources.yaml` (ADR-001). Sizes: median [min-max].",
        "",
        "## Files per source and class folder",
        "",
        "| Source | Role | Class folder | Label | Files | Unique SHA-256 | Unreadable | "
        "Formats | Modes | With transparent pixels | Width px | Height px | File KB |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for (source, folder), items in sorted(groups.items()):
        ok = [i for i in items if i.readable]
        labels = {i.raw.label for i in items}
        label = "/".join(LABEL_NAMES[x] for x in sorted(labels, key=str))
        lines.append(
            f"| {source} | {items[0].raw.role} | `{folder}` | {label} | {len(items)} | "
            f"{len({i.sha256 for i in items})} | {len(items) - len(ok)} | "
            f"{_counts(Counter(i.fmt for i in ok))} | {_counts(Counter(i.mode for i in ok))} | "
            f"{sum(i.transparent for i in ok)} | {_q([i.width for i in ok])} | "
            f"{_q([i.height for i in ok])} | {_q([i.size_bytes / 1024 for i in items])} |"
        )

    # Per-source unique-image totals and label balance (included, readable files only).
    lines += [
        "",
        "## Unique images per source (included, readable files; exact duplicates collapsed)",
        "",
        "| Source | Role | Files | Excluded by membership | Unique images | Authentic | "
        "Counterfeit | Unlabelled | SHA groups with conflicting labels |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    by_source: dict[str, list[FileInfo]] = defaultdict(list)
    for info in infos:
        by_source[info.raw.source].append(info)
    for source, items in sorted(by_source.items()):
        used = [i for i in items if i.readable and i.raw.included]
        sha_labels: dict[str, set[int | None]] = defaultdict(set)
        for i in used:
            sha_labels[i.sha256].add(i.raw.label)
        single = [next(iter(v)) for v in sha_labels.values() if len(v) == 1]
        conflicts = sum(1 for v in sha_labels.values() if len(v) > 1)
        lines.append(
            f"| {source} | {items[0].raw.role} | {len(items)} | "
            f"{sum(1 for i in items if not i.raw.included)} | {len(sha_labels)} | "
            f"{single.count(0)} | {single.count(1)} | {single.count(None)} | {conflicts} |"
        )

    # Within-source duplicates spanning class folders.
    lines += [
        "",
        "## Exact duplicates across class folders within a source",
        "",
        "Each row counts unique images whose identical copies sit in exactly this set of folders.",
        "",
        "| Source | Folders holding the same bytes | Unique images |",
        "|---|---|---|",
    ]
    for source, items in sorted(by_source.items()):
        folders_by_sha: dict[str, set[str]] = defaultdict(set)
        for i in items:
            folders_by_sha[i.sha256].add(i.raw.class_folder)
        spans = Counter(tuple(sorted(v)) for v in folders_by_sha.values() if len(v) > 1)
        for span, n in sorted(spans.items(), key=lambda kv: (-kv[1], kv[0])):
            lines.append(f"| {source} | {', '.join(f'`{s}`' for s in span)} | {n} |")
        copies = sum(len(v) for v in _sha_paths(items).values() if len(v) > 1)
        within = sum(
            1
            for paths in _sha_paths(items).values()
            if len(paths) > len({p.raw.class_folder for p in paths})
        )
        if copies:
            lines.append(
                f"| {source} | (any) files with an identical copy: {copies}; unique images "
                f"duplicated inside one folder: {within} | |"
            )

    # Cross-source exact overlap.
    sha_sets = {s: {i.sha256 for i in items} for s, items in by_source.items()}
    names = sorted(sha_sets)
    lines += [
        "",
        "## Exact duplicates across sources (unique SHA-256 shared)",
        "",
        "| Source | " + " | ".join(names) + " |",
        "|---|" + "---|" * len(names),
    ]
    for a in names:
        cells = [str(len(sha_sets[a] & sha_sets[b])) if a != b else "-" for b in names]
        lines.append(f"| {a} | " + " | ".join(cells) + " |")

    unreadable = [i for i in infos if not i.readable]
    lines += ["", "## Unreadable files", ""]
    if unreadable:
        lines += ["| File | Error |", "|---|---|"]
        lines += [f"| `{_rel(i.raw.path)}` | {i.error} |" for i in unreadable]
    else:
        lines.append("None.")
    lines += ["", "## Non-image files (not inventoried as images)", ""]
    lines += [f"- `{_rel(p)}`" for p in other_files] or ["None."]
    return "\n".join(lines) + "\n"


def _sha_paths(items: list[FileInfo]) -> dict[str, list[FileInfo]]:
    out: dict[str, list[FileInfo]] = defaultdict(list)
    for i in items:
        out[i.sha256].append(i)
    return out


def _rel(path: Path) -> str:
    return path.relative_to(REPO_ROOT).as_posix()


def main() -> int:
    """Scan, report, and return a process exit code."""
    configure_logging()
    cfg = OmegaConf.to_container(OmegaConf.load(CONFIG_DIR / "data" / "sources.yaml"))
    assert isinstance(cfg, dict)
    extensions = tuple(e.lower() for e in cfg["image_extensions"])
    raw_dir = REPO_ROOT / "data" / "raw"
    specs = load_specs(cfg, REPO_ROOT)
    raws = list_raw_files(raw_dir, specs, extensions)
    log.info("inspecting %d image files", len(raws))
    infos = [inspect(r) for r in raws]
    configured = {s.name for s in specs}
    other = sorted(
        p
        for p in raw_dir.rglob("*")
        if p.is_file()
        and (
            p.suffix.lower() not in extensions or p.relative_to(raw_dir).parts[0] not in configured
        )
    )
    out = REPO_ROOT / "results" / "tables" / "raw_inventory.md"
    atomic_write_text(out, render(infos, other))
    log.info("wrote %s", out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
