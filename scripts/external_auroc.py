"""EXPLORATORY, not pre-registered: threshold-free AUROC on the pooled external sets.

The Mendeley sets are all authentic and Split E all counterfeit, so pooling them gives a
two-class external set. Per arm: the run-averaged probability per external image, then AUROC
with a stratified bootstrap CI over images, plus the spread of per-run AUROCs and of the run
thresholds. Descriptive only: external sets never drive decisions (ADR-005).

Usage:
    python scripts/external_auroc.py --exp e01 --exp e02 --exp e03 --exp e04 --exp e05
"""

from __future__ import annotations

import argparse
import sys

import numpy as np
import pandas as pd

from pharmachecked.config import REPO_ROOT
from pharmachecked.evaluation.aggregate import RunRecord, collect_runs, to_markdown
from pharmachecked.evaluation.metrics import auroc
from pharmachecked.evaluation.stats import bootstrap_ci
from pharmachecked.utils.io import atomic_write_text
from pharmachecked.utils.logging import configure_logging, get_logger

log = get_logger(__name__)
POSITIVE_PREFIX = "split_e"  # counterfeit external sources


def arm_row(exp: str, records: list[RunRecord], n_boot: int) -> dict[str, object]:
    """External AUROC of one arm (``records`` = its runs)."""
    preds = pd.concat(
        pd.read_csv(r.root / "external_predictions.csv").assign(run=r.root.name) for r in records
    )
    preds["y"] = preds["source_dataset"].str.startswith(POSITIVE_PREFIX).astype(int)
    per_image = preds.groupby("image_id", as_index=False).agg(
        y=("y", "first"), prob=("prob", "mean")
    )
    ci = bootstrap_ci(
        per_image["y"].to_numpy(), (per_image["prob"].to_numpy(),), auroc, n_boot=n_boot
    )
    per_run = [auroc(g["y"], g["prob"]) for _, g in preds.groupby("run")]
    thresholds = [r.threshold for r in records]
    return {
        "config": f"{exp}:{records[0].model}/{records[0].variant}",
        "runs": len(records),
        "external images": len(per_image),
        "external AUROC (run-averaged)": f"{ci.estimate:.3f} [{ci.low:.3f}, {ci.high:.3f}]",
        "per-run AUROC mean ± sd": f"{np.mean(per_run):.3f} ± {np.std(per_run):.3f}",
        "per-run AUROC min-max": f"{min(per_run):.3f}-{max(per_run):.3f}",
        "run thresholds min-max": f"{min(thresholds):.3f}-{max(thresholds):.3f}",
    }


def main() -> int:
    """CLI entry point; returns a process exit code."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--exp", action="append", required=True)
    parser.add_argument("--n-boot", type=int, default=2000)
    args = parser.parse_args()
    configure_logging()
    rows = []
    for exp in args.exp:
        records = collect_runs(REPO_ROOT / "results" / "runs", exp)
        arms = sorted({(r.model, r.variant) for r in records})
        for model, variant in arms:
            arm = [r for r in records if (r.model, r.variant) == (model, variant)]
            rows.append(arm_row(exp, arm, args.n_boot))
    table = pd.DataFrame(rows)
    header = (
        "# External AUROC (EXPLORATORY, not pre-registered)\n\n"
        "Generated by `scripts/external_auroc.py`. Mendeley split_c and split_d (all authentic) "
        "pooled with Split E harvested and regulatory (all counterfeit). Run-averaged probability "
        f"per external image; 95% stratified bootstrap CI over images ({args.n_boot} resamples, "
        "seed 0). Per-run columns show how much equivalent trainings differ.\n\n"
        "Descriptive only: external sets never drive decisions (ADR-005). This AUROC also "
        "separates two acquisition sources (phone photos vs web images), not only the two "
        "classes.\n\n"
    )
    out = REPO_ROOT / "results" / "tables" / "external_auroc_exploratory.md"
    atomic_write_text(out, header + to_markdown(table))
    log.info("wrote %s (%d arms)", out.name, len(table))
    return 0


if __name__ == "__main__":
    sys.exit(main())
