"""Build the release and paper assets from committed tables and figures (PLAN 10.3, 10.5).

Writes, without training or reading any image:

* ``results/tables/leaderboard.md``: the E1 baseline ladder ranked by pooled out-of-fold AUROC,
  and the locked-test results of the frozen models (ADR-030) when ``final_test.csv`` exists;
* ``results/paper/``: Fig 1-8 (PNG + PDF) and Tab 1-4 (CSV + Markdown) copied under paper names,
  a ``README.md`` mapping each to its source, and ``numbers.json`` holding every cell of
  Tab 1-4, each with its source file.

``--weights DIR`` also packs the frozen checkpoints (``best.pt`` of the 15 fold models of each
frozen configuration, plus any ONNX files) into one zip per configuration under ``DIR`` with a
SHA-256 ``MANIFEST.json``, for attaching to a GitHub release. Weights never enter git.

Usage:
    python scripts/release_assets.py [--weights <folder outside the repo>]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
import zipfile
from pathlib import Path

import pandas as pd

from pharmachecked.config import REPO_ROOT
from pharmachecked.evaluation.aggregate import to_markdown

T = REPO_ROOT / "results" / "tables"
F = REPO_ROOT / "results" / "figures"
PAPER = REPO_ROOT / "results" / "paper"

FIGURES = {  # paper name -> (source figure stem, caption)
    "fig1": ("e01_auroc_vs_params", "E1 baseline ladder: pooled OOF AUROC vs parameters"),
    "fig2": ("e04_gate_weights_by_packaging", "E4 multi-branch model: gate weight per branch"),
    "fig3": ("e06_learning_curves", "E6 data efficiency: learning curves"),
    "fig4": ("e08_seen_vs_unseen", "E8 open set: seen vs held-out packaging type"),
    "fig5": ("e09_ext_severity_curves", "E9 robustness: AUROC vs corruption severity 1-8"),
    "fig6": ("e10_reliability_diagrams", "E10 calibration: reliability diagrams"),
    "fig7": ("e15_arms_race", "E15 adaptive adversary: arms race"),
    "fig8": ("e16_pareto", "E16 deployment: AUROC vs size and latency"),
}
TABLES = {  # paper name -> (source table stem, caption)
    "tab1": ("e01_summary", "E1 baseline ladder (5 folds x 3 seeds, OOF)"),
    "tab2": ("e04_vs_reference", "E4 ablations vs the full multi-branch model"),
    "tab3": ("e11_end_to_end", "E11 end-to-end system vs bare classifier"),
    "tab4": ("final_test", "Locked test set, frozen models (ADR-030)"),
}
FROZEN = {  # ADR-030 configuration -> final_test.csv model name
    "efficientnetv2-s/default": "final model (EfficientNetV2-S)",
    "convnext-tiny/ft": "E1 best (ConvNeXt-T, data v2)",
    "mobilenetv3-large/kd-t4": "E16 student (MobileNetV3-L, KD T=4)",
}
WEIGHT_PREFIXES = {
    "efficientnetv2-s_default": "e05_efficientnetv2-s_default_",
    "convnext-tiny_ft": "p4ref_convnext-tiny_ft_",
    "mobilenetv3-large_kd-t4": "e16_mobilenetv3-large_kd-t4_",
}


def read_table(stem: str) -> pd.DataFrame:
    """Read ``results/tables/<stem>`` as text: the CSV if present, else the Markdown table.

    Args:
        stem: Table name without extension.

    Returns:
        The table with every cell as text, exactly as written.

    Raises:
        FileNotFoundError: if neither file exists.
    """
    csv = T / f"{stem}.csv"
    if csv.is_file():
        return pd.read_csv(csv, dtype=str, keep_default_na=False)
    lines = (T / f"{stem}.md").read_text(encoding="utf-8").splitlines()
    rows = [ln for ln in lines if ln.startswith("|")]
    cells = [[c.strip() for c in ln.strip("|").split("|")] for ln in rows]
    return pd.DataFrame(cells[2:], columns=cells[0])


def leaderboard() -> str:
    """Markdown leaderboard: E1 ladder by pooled OOF AUROC, then the locked-test table."""
    e01 = read_table("e01_summary")
    point = e01["auroc (pooled)"].str.split(" ").str[0].astype(float)
    cols = ["config", "runs", "auroc (pooled)", "auroc (runs)", "auprc (pooled)",
            "ece (pooled)", "params (M)"]  # fmt: skip
    ranked = e01.assign(_p=point).sort_values("_p", ascending=False, kind="stable")[cols]
    ranked.insert(0, "rank", range(1, len(ranked) + 1))
    out = [
        "# Leaderboard\n",
        "Generated by `scripts/release_assets.py` from committed tables; numbers are pasted.\n",
        "## Development pool, out-of-fold (E1 baseline ladder)\n",
        "Ranked by the point estimate of the pooled AUROC (`results/tables/e01_summary.csv`); "
        "overlapping CIs mean the order among the top entries is not significant (see "
        "`e01_pairwise.md`).\n",
        to_markdown(ranked),
    ]
    if (T / "final_test.csv").is_file():
        ft = read_table("final_test")
        keep = ["model", "images", "AUROC (ensemble)", "AUPRC (ensemble)",
                "sens@95%spec (ensemble)", "balanced acc (per run, val threshold)",
                "conformal coverage (per run, alpha 0.10)"]  # fmt: skip
        out += [
            "\n## Locked test set (95 images, evaluated once)\n",
            "From `results/tables/final_test.csv`; paired DeLong tests in "
            "`final_test_pairwise.csv`.\n",
            to_markdown(ft[keep]),
        ]
    return "\n".join(out).rstrip("\n") + "\n"


def paper_assets() -> dict[str, dict[str, str]]:
    """Copy Fig 1-8 / Tab 1-4 into ``results/paper/`` and return ``numbers.json`` content."""
    PAPER.mkdir(parents=True, exist_ok=True)
    readme = ["# Paper assets\n", "Copied by `scripts/release_assets.py`; do not edit here.\n",
              "| asset | source | caption |", "|---|---|---|"]  # fmt: skip
    for name, (stem, caption) in FIGURES.items():
        for ext in ("png", "pdf"):
            shutil.copyfile(F / f"{stem}.{ext}", PAPER / f"{name}.{ext}")
        readme.append(f"| {name} | `results/figures/{stem}.{{png,pdf}}` | {caption} |")
    numbers: dict[str, dict[str, str]] = {}
    for name, (stem, caption) in TABLES.items():
        df = read_table(stem)
        df.to_csv(PAPER / f"{name}.csv", index=False, lineterminator="\n")
        (PAPER / f"{name}.md").write_text(
            f"# {name}: {caption}\n\n" + to_markdown(df).rstrip("\n") + "\n", encoding="utf-8"
        )
        src = f"results/tables/{stem}.{'csv' if (T / f'{stem}.csv').is_file() else 'md'}"
        readme.append(f"| {name} | `{src}` | {caption} |")
        key_col = df.columns[0]
        for _, row in df.iterrows():
            for col in df.columns[1:]:
                numbers[f"{name}/{row[key_col]}/{col}"] = {
                    "value": row[col],
                    "source": src,
                    "row": row[key_col],
                    "column": col,
                }
    (PAPER / "README.md").write_text("\n".join(readme) + "\n", encoding="utf-8")
    return numbers


def pack_weights(out_dir: Path) -> list[Path]:
    """Zip each frozen configuration's checkpoints with a SHA-256 manifest."""
    out_dir.mkdir(parents=True, exist_ok=True)
    ckpts = REPO_ROOT / "checkpoints"
    written = []
    for name, prefix in WEIGHT_PREFIXES.items():
        runs = sorted(p for p in ckpts.iterdir() if p.name.startswith(prefix))
        if len(runs) != 15:
            raise FileNotFoundError(f"{name}: {len(runs)} checkpoint folders, expected 15")
        manifest = {}
        zpath = out_dir / f"pharmachecked_weights_{name}.zip"
        with zipfile.ZipFile(zpath, "w", zipfile.ZIP_STORED) as zf:
            for run in runs:
                for f in sorted(run.iterdir()):
                    arc = f"{run.name}/{f.name}"
                    manifest[arc] = hashlib.sha256(f.read_bytes()).hexdigest()
                    zf.write(f, arc)
            zf.writestr("MANIFEST.json", json.dumps(manifest, indent=1, sort_keys=True) + "\n")
        written.append(zpath)
    return written


def main() -> int:
    """Write the leaderboard and paper assets; optionally pack the weights."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--weights", type=Path, help="folder outside the repo for weight zips")
    args = parser.parse_args()
    (T / "leaderboard.md").write_text(leaderboard(), encoding="utf-8")
    numbers = paper_assets()
    (PAPER / "numbers.json").write_text(
        json.dumps(numbers, indent=1, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    if args.weights:
        if args.weights.resolve().is_relative_to(REPO_ROOT):
            sys.stderr.write("refused: weights must be written outside the repository\n")
            return 2
        for z in pack_weights(args.weights):
            sys.stderr.write(f"wrote {z} ({z.stat().st_size / 1e6:.0f} MB)\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
