"""Generate the data-card tables (PLAN 1.10) and refresh them inside docs/DATA_CARD.md.

Writes results/tables/data_card_counts.md and replaces the block between
``<!-- BEGIN generated -->`` and ``<!-- END generated -->`` in docs/DATA_CARD.md with it, so
every number in the data card comes from this script.

Usage:
    python scripts/data_card_tables.py
"""

from __future__ import annotations

import re
import sys

import pandas as pd

from pharmachecked.config import REPO_ROOT
from pharmachecked.data.annotations import PACKAGING_TYPES
from pharmachecked.data.manifest import read_manifest
from pharmachecked.utils.io import atomic_write_text
from pharmachecked.utils.logging import configure_logging, get_logger

log = get_logger("data_card_tables")
BLOCK = re.compile(r"<!-- BEGIN generated -->.*<!-- END generated -->", re.DOTALL)


def _q(s: pd.Series) -> str:
    return f"{int(s.median())} [{int(s.min())}-{int(s.max())}]"


def tables(dev: pd.DataFrame, ext: pd.DataFrame) -> str:
    """Markdown tables: per source/class, per partition, sizes, packaging types."""
    both = pd.concat([dev.assign(role="development"), ext.assign(role="external")])
    lines = [
        "### Unique images per source",
        "",
        "| Source | Role | Images | Authentic | Counterfeit |",
        "|---|---|---|---|---|",
    ]
    for (source, role), g in both.groupby(["source_dataset", "role"]):
        lines.append(
            f"| {source} | {role} | {len(g)} | {int((g.label == 0).sum())} | "
            f"{int((g.label == 1).sum())} |"
        )
    lines += [
        "",
        "### Development pool by partition (splits/v1.json)",
        "",
        "| Partition | Images | Authentic | Counterfeit | Near-duplicate groups |",
        "|---|---|---|---|---|",
    ]
    for name, g in dev.groupby("split"):
        lines.append(
            f"| {name} | {len(g)} | {int((g.label == 0).sum())} | {int((g.label == 1).sum())} | "
            f"{g.group_id.nunique()} |"
        )
    lines += [
        "",
        "### Normalized image size (pixels, median [min-max])",
        "",
        "| Source | Class | Width | Height |",
        "|---|---|---|---|",
    ]
    for (source, label), g in both.groupby(["source_dataset", "label"]):
        cls = "counterfeit" if label else "authentic"
        lines.append(f"| {source} | {cls} | {_q(g.width)} | {_q(g.height)} |")
    lines += ["", "### Packaging type (development pool, human-reviewed)", ""]
    labelled = dev[dev.packaging_type != ""]
    if len(labelled) < len(dev):
        lines.append(
            f"Pending: {len(labelled)} of {len(dev)} images have a reviewed packaging type "
            "(PLAN 1.7)."
        )
    else:
        lines += ["| Packaging type | Authentic | Counterfeit |", "|---|---|---|"]
        for t in PACKAGING_TYPES:
            g = dev[dev.packaging_type == t]
            lines.append(f"| {t} | {int((g.label == 0).sum())} | {int((g.label == 1).sum())} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    """Write the table file and refresh the data card; returns a process exit code."""
    configure_logging()
    processed = REPO_ROOT / "data" / "processed"
    text = tables(
        read_manifest(processed / "manifest_v1.csv"),
        read_manifest(processed / "manifest_external_v1.csv"),
    )
    atomic_write_text(
        REPO_ROOT / "results" / "tables" / "data_card_counts.md",
        "# Data card counts (generated by scripts/data_card_tables.py)\n\n" + text,
    )
    card = REPO_ROOT / "docs" / "DATA_CARD.md"
    body = card.read_text(encoding="utf-8")
    if not BLOCK.search(body):
        log.error("%s has no generated block", card)
        return 1
    block = f"<!-- BEGIN generated -->\n{text}<!-- END generated -->"
    atomic_write_text(card, BLOCK.sub(lambda _: block, body))
    log.info("refreshed data_card_counts.md and the DATA_CARD.md block")
    return 0


if __name__ == "__main__":
    sys.exit(main())
