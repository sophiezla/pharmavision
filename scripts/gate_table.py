"""Tabulate mean gate weight per branch per packaging type from branch_outputs.csv (PLAN 3.7).

Reads the ``branch_outputs.csv`` files written by ``scripts/predict_branch_outputs.py`` and
writes ``results/tables/<exp>_gate_weights.{csv,md}``.

Usage:
    python scripts/gate_table.py --exp e04 --model multibranch --variant full
"""

from __future__ import annotations

import argparse
import sys

import pandas as pd

from pharmachecked.config import REPO_ROOT
from pharmachecked.evaluation.aggregate import collect_runs, to_markdown
from pharmachecked.evaluation.branch_outputs import BRANCH_FILE, gate_table
from pharmachecked.utils.io import atomic_write_text, read_json
from pharmachecked.utils.logging import configure_logging, get_logger

log = get_logger("gate_table")


def main() -> int:
    """CLI entry point; returns a process exit code."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--exp", required=True)
    parser.add_argument("--model", required=True)
    parser.add_argument("--variant", required=True)
    args = parser.parse_args()
    configure_logging()
    runs = [
        r
        for r in collect_runs(REPO_ROOT / "results" / "runs", args.exp)
        if (r.model, r.variant) == (args.model, args.variant)
    ]
    missing = [r.root.name for r in runs if not (r.root / BRANCH_FILE).is_file()]
    if not runs or missing:
        n_missing = len(missing)
        log.error("%d runs, %d without %s: %s", len(runs), n_missing, BRANCH_FILE, missing[:1])
        return 1
    table = gate_table(pd.read_csv(r.root / BRANCH_FILE) for r in runs)
    check = REPO_ROOT / "results" / "pipeline" / f"{args.exp}_{args.variant}_branch_outputs.json"
    worst = max(v["max_abs_prob_diff"] for v in read_json(check)["runs"].values())
    tables = REPO_ROOT / "results" / "tables"
    stem = f"{args.exp}_gate_weights"
    table.to_csv(tables / f"{stem}.csv", index=False, lineterminator="\n", float_format="%.4f")
    shown = table.assign(
        gate=[f"{m:.3f} ± {s:.3f}" for m, s in zip(table["mean"], table["sd"], strict=True)]
    )
    wide = shown.pivot(index="packaging_type", columns="branch", values="gate")
    counts = table.groupby("packaging_type")["images"].first()
    wide = wide.join(counts).reset_index()
    atomic_write_text(
        tables / f"{stem}.md",
        f"# {args.exp}: mean fusion gate weight per branch per packaging type\n\n"
        f"Generated by `scripts/gate_table.py` from the `{BRANCH_FILE}` of {len(runs)} "
        f"`{args.model}/{args.variant}` runs (held-out folds re-predicted from the saved "
        "checkpoints by `scripts/predict_branch_outputs.py`). Per run: mean gate weight over "
        "the held-out images of each packaging type; shown: mean ± sd over runs. `images` = "
        "held-out images of that type in one seed's five folds. Largest absolute difference "
        f"between re-predicted and original OOF probabilities over all runs: {worst:.2e} "
        f"(`{check.relative_to(REPO_ROOT).as_posix()}`).\n\n" + to_markdown(wide),
    )
    log.info("wrote %s.{csv,md}", stem)
    return 0


if __name__ == "__main__":
    sys.exit(main())
