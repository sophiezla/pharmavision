"""Build the E12-E16 tables from the run folders of the combined kit (ADR-027).

The training-arm tables use scripts/aggregate.py, e.g.
    python scripts/aggregate.py --exp e14 --include e05:efficientnetv2-s/default \
        --reference efficientnetv2-s/default

Usage:
    python scripts/phase6to8_tables.py --exp e12|e13|e14|e15|e16 [--prefix st]
"""

from __future__ import annotations

import argparse
import sys

import pandas as pd

from pharmachecked.config import REPO_ROOT
from pharmachecked.evaluation import phase6to8 as t
from pharmachecked.evaluation.aggregate import collect_runs, to_markdown
from pharmachecked.pipeline.combined import PROFILES, arm_runs, refs
from pharmachecked.utils.io import atomic_write_text, read_json
from pharmachecked.utils.logging import configure_logging, get_logger

log = get_logger("phase6to8_tables")
TABLES = REPO_ROOT / "results" / "tables"
RUNS = REPO_ROOT / "results" / "runs"


def _write(stem: str, title: str, note: str, table: pd.DataFrame) -> None:
    if table.empty:
        log.warning("%s: no data", stem)
        return
    table.to_csv(TABLES / f"{stem}.csv", index=False, lineterminator="\n")
    atomic_write_text(
        TABLES / f"{stem}.md",
        f"# {title}\n\nGenerated by `scripts/phase6to8_tables.py`. {note}\n\n" + to_markdown(table),
    )
    log.info("wrote %s.{csv,md}", stem)


def _by_variant(exp: str) -> dict[str, list]:
    out: dict[str, list] = {}
    for r in collect_runs(RUNS, exp):
        out.setdefault(f"{r.model}/{r.variant}", []).append(r)
    return out


def main() -> int:
    """CLI entry point; returns a process exit code."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--exp", required=True, choices=("e12", "e13", "e14", "e15", "e16"))
    parser.add_argument("--prefix", default="", help="'st' for the self-test experiments")
    args = parser.parse_args()
    configure_logging()
    p = PROFILES["selftest" if args.prefix else "full"]
    s = args.prefix

    if args.exp == "e12":
        models = {
            "final": refs(p, "final"),
            "DINOv2-S": refs(p, "vit"),
            "E4 multi-branch": refs(p, "mil"),
        }
        _write(
            f"{s}e12_faithfulness",
            "E12: deletion / insertion AUC per model and method",
            "Every held-out image of every fold model; mean ± sd over fold models of the per-run "
            "mean. p: Wilcoxon signed-rank of the per-image difference to the random map, Holm "
            "over all tests (E12.md).",
            t.e12_faithfulness(models),
        )
        _write(
            f"{s}e12_randomization",
            "E12: cascading model randomization (Spearman with the original maps)",
            "Fold 0 / seed 0, first 50 held-out images in image-id order (E12.md).",
            t.e12_randomization(models),
        )
        _write(
            f"{s}e12_localization",
            "E12: localization of E14 edits",
            "Synthetic counterfeits whose source is in the fold model's held-out fold; mean ± sd "
            "over fold models (PLAN 6.3).",
            t.e12_localization(models),
        )
    elif args.exp == "e13":
        arms = _by_variant(f"{s}e13")
        _write(
            f"{s}e13_concepts",
            "E13: concept prediction AUROC per concept",
            "Annotated held-out images, seed-averaged predictions (E13.md).",
            t.e13_concepts(arms),
        )
        _write(
            f"{s}e13_intervention",
            "E13: task AUROC after intervening on the k most uncertain concepts",
            "Annotated held-out images, seed-averaged (PLAN 6.6).",
            t.e13_intervention(arms),
        )
        seed0 = [r for r in refs(p, "final") if r.seed == 0]
        _write(
            f"{s}e13_tcav",
            "E13: TCAV on the final model",
            "Seed-0 fold models; a concept counts as used when significant (Holm) in at least 3 "
            "of the 5 fold models (E13.md).",
            t.e13_tcav(seed0),
        )
    elif args.exp == "e14":
        best = REPO_ROOT / "results" / "pipeline" / f"{s}e14_best.json"
        counts = REPO_ROOT / "results" / "pipeline" / f"{s}e14_synthesis_counts.csv"
        if counts.is_file():
            _write(
                f"{s}e14_synthesis",
                "E14: synthetic images per generator and edit type",
                "From the kit's synthetic manifest.",
                pd.read_csv(counts),
            )
        if best.is_file():
            decision = read_json(best)
            _write(
                f"{s}e14_best",
                "E14: best ratio arm (pre-registered decision)",
                f"Chosen: `{decision['variant']}` (E14.md rule).",
                pd.DataFrame(decision["ranking"]),
            )
        log.info("summary and open-set tables: scripts/aggregate.py --exp %se14 / %se14os", s, s)
    elif args.exp == "e15":
        best = read_json(REPO_ROOT / "results" / "pipeline" / f"{s}e14_best.json")
        defences = {
            "none": refs(p, "final"),
            "synth (E14 best)": arm_runs(f"{s}e14", "efficientnetv2-s", str(best["variant"])),
            "adv": arm_runs(f"{s}e15", "efficientnetv2-s", "adv"),
            "both": arm_runs(f"{s}e15", "efficientnetv2-s", "both"),
        }
        _write(
            f"{s}e15_defences",
            "E15: evasion rates per defence and attack",
            "Held-out counterfeits detected when clean; evasion = probability below the fold "
            "model's val-selected threshold; mean ± sd over fold models (E15.md).",
            t.e15_defences(defences),
        )
        rounds = {
            int(v.removeprefix("efficientnetv2-s/round")): recs
            for v, recs in _by_variant(f"{s}e15race").items()
        }
        _write(
            f"{s}e15_arms_race",
            "E15: arms race",
            "Held-out evasion rate of a fresh 200-query search per round; mean ± sd over the "
            "15 fold/seed lineages (E15.md).",
            t.e15_arms_race(rounds),
        )
    else:
        arms = _by_variant(f"{s}e16")
        arms["final model"] = refs(p, "final")
        _write(
            f"{s}e16_deployment",
            "E16: exported models (ONNX FP32 / INT8)",
            "Held-out probabilities of the exported models, seed-averaged; latency and the "
            "re-fitted reliability metrics are added on the laptop (PLAN 8.3-8.4).",
            t.e16_deployment(arms),
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
