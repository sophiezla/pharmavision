"""Aggregate an experiment's run folders into results/tables/{exp}_summary.* and _pairwise.md.

Usage:
    python scripts/aggregate.py --exp e01 [--n-boot 2000]
"""

from __future__ import annotations

import argparse
import sys

from pharmachecked.config import REPO_ROOT
from pharmachecked.evaluation.aggregate import (
    collect_runs,
    pairwise_vs_best,
    pairwise_vs_reference,
    summarize,
    to_markdown,
)
from pharmachecked.utils.io import atomic_write_text
from pharmachecked.utils.logging import configure_logging, get_logger

log = get_logger("aggregate")


def main() -> int:
    """CLI entry point; returns a process exit code."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--exp", required=True)
    parser.add_argument("--n-boot", type=int, default=2000)
    parser.add_argument(
        "--include",
        action="append",
        default=[],
        metavar="EXP:MODEL/VARIANT",
        help="also include one arm of another experiment (e.g. e01:convnext-tiny/ft for E2)",
    )
    parser.add_argument(
        "--reference",
        metavar="MODEL/VARIANT",
        help="also compare every configuration with this one (writes <exp>_vs_reference.md)",
    )
    args = parser.parse_args()
    configure_logging()
    runs_dir = REPO_ROOT / "results" / "runs"
    records = collect_runs(runs_dir, args.exp)
    if not records:
        log.error("no complete, clean runs for %s", args.exp)
        return 1
    included = []
    for spec in args.include:
        exp, arm = spec.split(":", 1)
        model, variant = arm.split("/", 1)
        found = [r for r in collect_runs(runs_dir, exp) if (r.model, r.variant) == (model, variant)]
        if not found:
            log.error("no runs for %s", spec)
            return 1
        records += found
        included.append(f"`{spec}` ({len(found)} runs)")
    summary, pooled = summarize(records, args.n_boot)
    pairwise = pairwise_vs_best(pooled, args.n_boot)
    tables = REPO_ROOT / "results" / "tables"
    header = (
        f"# {args.exp}: summary\n\n"
        + (f"Includes runs from other experiments: {', '.join(included)}.\n\n" if included else "")
        + f"Generated by `scripts/aggregate.py` from {len(records)} "
        "complete, clean run folders. Per-run metrics: mean ± std over runs on the held-out fold. "
        "Pooled: seed-averaged OOF probability per image, 95% stratified bootstrap CI "
        f"({args.n_boot} resamples, seed 0). External columns: run-averaged specificity or recall "
        "with a bootstrap CI over images (ADR-005).\n\n"
    )
    summary.to_csv(tables / f"{args.exp}_summary.csv", index=False, lineterminator="\n")
    atomic_write_text(tables / f"{args.exp}_summary.md", header + to_markdown(summary))
    atomic_write_text(
        tables / f"{args.exp}_pairwise.md",
        f"# {args.exp}: each configuration vs the best pooled AUROC\n\nPaired DeLong on pooled "
        "OOF predictions, Holm-corrected within the experiment; AUROC difference (best minus "
        "configuration) with a paired bootstrap CI. 'Improvement' requires Holm p < 0.05 and a "
        "CI excluding 0.\n\n" + to_markdown(pairwise),
    )
    if args.reference:
        vs = pairwise_vs_reference(pooled, args.reference, args.n_boot)
        atomic_write_text(
            tables / f"{args.exp}_vs_reference.md",
            f"# {args.exp}: each configuration vs `{args.reference}`\n\nPaired over the images "
            "both configurations have (pooled seed-averaged OOF predictions). Differences are "
            "configuration minus reference with paired bootstrap CIs "
            f"({args.n_boot} resamples); DeLong p Holm-corrected over the comparisons. "
            "'improves' / 'worse' = Holm p < 0.05 and an AUROC-difference CI above / below 0 "
            "(CLAUDE.md section 5). Lower ECE and log-loss are better.\n\n" + to_markdown(vs),
        )
    log.info("wrote %s_summary.{csv,md} and %s_pairwise.md", args.exp, args.exp)
    return 0


if __name__ == "__main__":
    sys.exit(main())
