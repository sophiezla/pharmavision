"""Build the Phase 4 tables from run folders: E7 transfer, E8 open set, E9 robustness.

E6 uses scripts/aggregate.py (its 100% arm comes from the p4ref and e05 runs):
    python scripts/aggregate.py --exp e06 --include p4ref:handcrafted-xgb/default ...

Usage:
    python scripts/phase4_tables.py --exp e07
    python scripts/phase4_tables.py --exp e08
    python scripts/phase4_tables.py --exp e09
    (--prefix st reads the self-test experiments stp4ref, ste07, ...)
"""

from __future__ import annotations

import argparse
import sys

import pandas as pd

from pharmachecked.config import REPO_ROOT
from pharmachecked.data.corruptions import load_corruption_config
from pharmachecked.evaluation.aggregate import collect_runs, to_markdown
from pharmachecked.evaluation.phase4 import e07_table, e08_table, e09_summaries
from pharmachecked.evaluation.robustness import CORRUPTION_FILE, severity_table
from pharmachecked.pipeline.phase4 import COMPARISON, E8_TYPES, FINAL
from pharmachecked.utils.io import atomic_write_text
from pharmachecked.utils.logging import configure_logging, get_logger

log = get_logger("phase4_tables")
RUNS = REPO_ROOT / "results" / "runs"
TABLES = REPO_ROOT / "results" / "tables"


def _reference(prefix: str) -> list:
    """Within-source 5-fold runs of the five comparison models (p4ref + the final model)."""
    keys = {a.key for a in COMPARISON}
    refs = [r for r in collect_runs(RUNS, f"{prefix}p4ref") if (r.model, r.variant) in keys]
    final_exp = "e05" if not prefix else f"{prefix}p4ref"
    if final_exp != f"{prefix}p4ref":
        refs += [r for r in collect_runs(RUNS, final_exp) if (r.model, r.variant) == FINAL.key]
    return refs


def _write(stem: str, title: str, note: str, table: pd.DataFrame) -> None:
    table.to_csv(TABLES / f"{stem}.csv", index=False, lineterminator="\n")
    atomic_write_text(
        TABLES / f"{stem}.md",
        f"# {title}\n\nGenerated by `scripts/phase4_tables.py`. {note}\n\n" + to_markdown(table),
    )
    log.info("wrote %s.{csv,md}", stem)


def main() -> int:
    """CLI entry point; returns a process exit code."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--exp", required=True, choices=("e07", "e08", "e09"))
    parser.add_argument("--prefix", default="", help="'st' for the self-test experiments")
    parser.add_argument("--n-boot", type=int, default=2000)
    args = parser.parse_args()
    configure_logging()
    p, nb = args.prefix, args.n_boot
    refs = _reference(p)
    boot = f"95% stratified bootstrap CIs ({nb} resamples, seed 0)"
    if args.exp == "e07":
        table = e07_table(collect_runs(RUNS, f"{p}e07"), refs, nb)
        _write(
            f"{p}e07_transfer",
            "E7: cross-dataset transfer, Kaggle -> pooled external sets (ADR-022)",
            "In-source: seed-averaged within-source 5-fold OOF predictions. Cross-source: models "
            "trained on the whole development pool, seed-averaged probabilities on Mendeley "
            "split_c + split_d (authentic) and Split E (counterfeit); specificity on the "
            "authentic and recall on the counterfeit images at the val-selected threshold, "
            f"averaged over runs. Drop CI resamples the two image "
            f"sets independently. {boot}. The cross-source AUROC also separates acquisition "
            "sources (ADR-005).",
            table,
        )
    elif args.exp == "e08":
        table = e08_table(collect_runs(RUNS, f"{p}e08"), refs, list(E8_TYPES), nb)
        _write(
            f"{p}e08_open_set",
            "E8: open set, leave one packaging type out",
            "Unseen: trained without the type (groups containing it removed), tested on every "
            "development image of the type; seed-averaged. Seen: the type's images in the "
            "within-source 5-fold OOF predictions (supervised models only). One-class methods "
            "(prototype-dinov2, patchcore) were fitted on authentic training images only; their "
            f"scores are monotone maps, so only ranking metrics are shown. {boot}.",
            table,
        )
    else:
        cfg = load_corruption_config()
        runs = [r for r in refs if (r.root / CORRUPTION_FILE).is_file()]
        if len(runs) != len(refs):
            log.warning("%d of %d fold models have corruption predictions", len(runs), len(refs))
        frames: dict[str, list[pd.DataFrame]] = {}
        for r in runs:
            frames.setdefault(f"{r.model}/{r.variant}", []).append(
                pd.read_csv(r.root / CORRUPTION_FILE)
            )
        severity = severity_table(frames, nb)
        final = "/".join(FINAL.key)
        mean, limits = e09_summaries(severity, final, float(cfg.quality_auroc))
        note = (
            "Fold models re-predict their own held-out fold under each corruption (applied "
            "after the evaluation geometry; `configs/eval/corruptions.yaml`); pooled "
            f"seed-averaged AUROC. {boot}. Runs: {len(runs)}."
        )
        _write(f"{p}e09_severity", "E9: AUROC per corruption and severity", note, severity)
        _write(f"{p}e09_mean_corruption_auroc", "E9: mean corruption AUROC", note, mean)
        _write(
            f"{p}e09_quality_limits",
            f"E9: quality limits of the final model ({final})",
            f"Highest severity s such that pooled AUROC >= {cfg.quality_auroc} at every "
            "severity 1..s (ADR-023); 0 = severity 1 already below. " + note,
            limits,
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
