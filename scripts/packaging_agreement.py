"""CLIP-vs-human packaging-type agreement (PLAN 1.7) and manifest update.

Once every image in data/annotations/packaging_type.csv has a final label, writes
results/tables/packaging_label_agreement.md (agreement, Cohen's kappa, confusion matrix) and
fills the manifest's packaging_type column. Before that, reports progress and exits 1.

Usage:
    python scripts/packaging_agreement.py
"""

from __future__ import annotations

import sys

import pandas as pd
from sklearn.metrics import cohen_kappa_score

from pharmachecked.config import REPO_ROOT
from pharmachecked.data.annotations import PACKAGING_TYPES, PackagingStore
from pharmachecked.data.manifest import read_manifest, write_manifest
from pharmachecked.utils.io import atomic_write_text
from pharmachecked.utils.logging import configure_logging, get_logger

log = get_logger("packaging_agreement")


def agreement_markdown(df: pd.DataFrame) -> str:
    """Agreement table for rows with ``clip_label`` and ``final_label``."""
    clip, human = df["clip_label"], df["final_label"]
    lines = [
        "# Packaging type: CLIP pre-label vs human label (PLAN 1.7)",
        "",
        "Generated by `scripts/packaging_agreement.py` from `data/annotations/packaging_type.csv`.",
        'CLIP ViT-B/16 (OpenAI), zero-shot prompts "a photo of a medicine {type}".',
        "",
        f"Images: {len(df)}; agreement: {100 * (clip == human).mean():.1f}%; "
        f"Cohen's kappa: {cohen_kappa_score(clip, human, labels=list(PACKAGING_TYPES)):.3f}.",
        "",
        "## Human label counts",
        "",
        "| Packaging type | Images |",
        "|---|---|",
        *(f"| {t} | {int((human == t).sum())} |" for t in PACKAGING_TYPES),
        "",
        "## Confusion matrix (rows: human, columns: CLIP)",
        "",
        "| Human \\ CLIP | " + " | ".join(PACKAGING_TYPES) + " |",
        "|---|" + "---|" * len(PACKAGING_TYPES),
    ]
    for t in PACKAGING_TYPES:
        counts = [int(((human == t) & (clip == c)).sum()) for c in PACKAGING_TYPES]
        lines.append(f"| {t} | " + " | ".join(map(str, counts)) + " |")
    return "\n".join(lines) + "\n"


def main() -> int:
    """Write the agreement table and update the manifest; returns a process exit code."""
    configure_logging()
    store = PackagingStore(REPO_ROOT / "data" / "annotations" / "packaging_type.csv")
    if store.n_done() < len(store.ids()):
        log.error(
            "%d of %d images labelled; finish the review first", store.n_done(), len(store.ids())
        )
        return 1
    df = store.df.reset_index(drop=True)
    atomic_write_text(
        REPO_ROOT / "results" / "tables" / "packaging_label_agreement.md", agreement_markdown(df)
    )
    path = REPO_ROOT / "data" / "processed" / "manifest_v1.csv"
    manifest = read_manifest(path)
    final = dict(zip(df["image_id"], df["final_label"], strict=True))
    manifest["packaging_type"] = manifest["image_id"].map(final)
    write_manifest(manifest, path)
    log.info("wrote packaging_label_agreement.md and filled packaging_type in %s", path.name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
