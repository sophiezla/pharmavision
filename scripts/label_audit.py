"""E3 label audit (PLAN 2.12): flag likely label issues for Sophie's review.

The E1-best arm is chosen with the pre-registered ranking (pooled OOF AUROC, exact ties ->
pooled OOF log-loss) over all trained E1 arms. Its seed-averaged OOF probabilities go into
``cleanlab.filter.find_label_issues`` (Northcutt et al., 2021; default prune-by-noise-rate,
ranked by self-confidence). The two images tagged ``not_a_drug`` (ADR-007) are added. Writes
data/annotations/label_audit.csv (decisions empty, for the app) and
results/tables/e03_flagged.md. Development images only; the locked test set is never audited.

Usage:
    python scripts/label_audit.py
"""

from __future__ import annotations

import sys

import numpy as np
import pandas as pd
from cleanlab.filter import find_label_issues

from pharmachecked.config import REPO_ROOT
from pharmachecked.data.manifest import read_manifest
from pharmachecked.evaluation.aggregate import collect_runs, pooled_oof
from pharmachecked.pipeline.decisions import ArmScore, rank, score_arms
from pharmachecked.utils.io import atomic_write_text
from pharmachecked.utils.logging import configure_logging, get_logger

log = get_logger("label_audit")
AUDIT = REPO_ROOT / "data" / "annotations" / "label_audit.csv"
COLUMNS = [
    "image_id",
    "original_label",
    "flagged_by",
    "model_prob",
    "decision",
    "new_label",
    "reason",
    "annotator",
    "timestamp",
]


def main() -> int:
    """Flag images and write the audit sheet; returns a process exit code."""
    configure_logging()
    if AUDIT.exists():
        log.error("%s exists; refusing to overwrite audit decisions", AUDIT)
        return 1
    records = [
        r for r in collect_runs(REPO_ROOT / "results" / "runs", "e01") if r.variant != "zeroshot"
    ]
    arms = {(r.model, r.variant) for r in records}
    best: ArmScore = rank(score_arms(records, dict.fromkeys(arms, 0)))[0]
    pooled = pooled_oof([r for r in records if (r.model, r.variant) == (best.model, best.variant)])
    labels = pooled["y_true"].to_numpy()
    probs = np.column_stack([1 - pooled["prob"], pooled["prob"]])
    issues = find_label_issues(labels, probs, return_indices_ranked_by="self_confidence")
    flagged = pooled.iloc[issues][["image_id", "y_true", "prob"]].assign(flagged_by="cleanlab")

    manifest = read_manifest(REPO_ROOT / "data" / "processed" / "manifest_v1.csv")
    dev = manifest[manifest["split"] == "dev"]
    not_drug = dev[dev["packaging_type"] == "not_a_drug"]
    prob_of = dict(zip(pooled["image_id"], pooled["prob"], strict=True))
    extra = pd.DataFrame(
        {
            "image_id": not_drug["image_id"],
            "y_true": not_drug["label"],
            "prob": not_drug["image_id"].map(prob_of),
            "flagged_by": "not_a_drug",
        }
    )
    sheet = (
        pd.concat([flagged, extra])
        .groupby("image_id", as_index=False)
        .agg(
            y_true=("y_true", "first"), prob=("prob", "first"), flagged_by=("flagged_by", "+".join)
        )
    )
    sheet = sheet.rename(columns={"y_true": "original_label", "prob": "model_prob"})
    for col in ("decision", "new_label", "reason", "annotator", "timestamp"):
        sheet[col] = ""
    sheet["model_prob"] = sheet["model_prob"].map(lambda p: f"{p:.4f}")
    AUDIT.parent.mkdir(parents=True, exist_ok=True)
    atomic_write_text(AUDIT, sheet[COLUMNS].to_csv(index=False, lineterminator="\n"))

    lines = [
        "# E3: images flagged for label review (PLAN 2.12)",
        "",
        f"Generated by `scripts/label_audit.py`. E1-best arm by the pre-registered ranking: "
        f"`{best.model}/{best.variant}` (pooled OOF AUROC {best.auroc:.4f}, log-loss "
        f"{best.log_loss:.4f}, {best.runs} runs). cleanlab {__import__('cleanlab').__version__} "
        "`find_label_issues` (prune by noise rate, ranked by self-confidence) on its "
        "seed-averaged OOF probabilities over the development pool, plus the images tagged "
        "`not_a_drug`.",
        "",
        "| Flagged by | Authentic | Counterfeit | Total |",
        "|---|---|---|---|",
    ]
    for source, part in sheet.groupby("flagged_by"):
        n_cf = int((part["original_label"] == 1).sum())
        lines.append(f"| {source} | {len(part) - n_cf} | {n_cf} | {len(part)} |")
    lines.append(
        f"| all | {int((sheet['original_label'] == 0).sum())} | "
        f"{int((sheet['original_label'] == 1).sum())} | {len(sheet)} |"
    )
    atomic_write_text(REPO_ROOT / "results" / "tables" / "e03_flagged.md", "\n".join(lines) + "\n")
    log.info("flagged %d images for review (best arm %s/%s)", len(sheet), best.model, best.variant)
    return 0


if __name__ == "__main__":
    sys.exit(main())
