"""Build the Phase 5 tables from run folders: E10, E11 and the E9 extension (ADR-024).

Usage:
    python scripts/phase5_tables.py --exp e10
    python scripts/phase5_tables.py --exp e11      (after e10: uses the chosen conformal method)
    python scripts/phase5_tables.py --exp e09ext
    (--prefix st reads the self-test experiments)
"""

from __future__ import annotations

import argparse
import json
import sys

import pandas as pd

from pharmachecked.config import REPO_ROOT
from pharmachecked.data.corruptions import load_corruption_config
from pharmachecked.evaluation import reliability as rel
from pharmachecked.evaluation.aggregate import to_markdown
from pharmachecked.evaluation.reliability_pass import RELIABILITY_FILE
from pharmachecked.evaluation.robustness import (
    CORRUPTION_FILE,
    EXTENSION_FILE,
    quality_limits,
    severity_table,
)
from pharmachecked.pipeline import phase4
from pharmachecked.utils.io import atomic_write_text, write_json
from pharmachecked.utils.logging import configure_logging, get_logger

log = get_logger("phase5_tables")
TABLES = REPO_ROOT / "results" / "tables"
DATA_DIR = REPO_ROOT / "data"
FINAL = "/".join(phase4.FINAL.key)


def _write(stem: str, title: str, note: str, table: pd.DataFrame) -> None:
    table.to_csv(TABLES / f"{stem}.csv", index=False, lineterminator="\n")
    atomic_write_text(
        TABLES / f"{stem}.md",
        f"# {title}\n\nGenerated by `scripts/phase5_tables.py`. {note}\n\n" + to_markdown(table),
    )
    log.info("wrote %s.{csv,md}", stem)


def _runs(prefix: str, filename: str) -> list:
    profile = phase4.PROFILES["selftest" if prefix else "full"]
    runs = phase4.e9_runs(profile)
    done = [r for r in runs if (r.root / filename).is_file()]
    if len(done) != len(runs):
        log.warning("%d of %d fold models have %s", len(done), len(runs), filename)
    return done


def main() -> int:
    """CLI entry point; returns a process exit code."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--exp", required=True, choices=("e10", "e11", "e09ext"))
    parser.add_argument("--prefix", default="", help="'st' for the self-test experiments")
    parser.add_argument("--n-boot", type=int, default=2000)
    args = parser.parse_args()
    configure_logging()
    p, nb = args.prefix, args.n_boot
    final = FINAL
    choice_file = TABLES / f"{p}e10_conformal_choice.json"

    if args.exp == "e09ext":
        runs = _runs(p, EXTENSION_FILE)
        frames: dict[str, list[pd.DataFrame]] = {}
        for r in runs:
            files = [r.root / f for f in (CORRUPTION_FILE, EXTENSION_FILE)]
            both = pd.concat([pd.read_csv(f) for f in files if f.is_file()])
            frames.setdefault(f"{r.model}/{r.variant}", []).append(both)
        severity = severity_table(frames, nb)
        cfg = load_corruption_config()
        note = (
            "Severities 1-5 as pre-registered (E09.md) plus 6-8 (ADR-024, PLAN 4.11); same fold "
            f"models, pooled seed-averaged AUROC, 95% stratified bootstrap CIs ({nb} resamples, "
            f"seed 0). Runs: {len(runs)}."
        )
        _write(
            f"{p}e09_ext_severity",
            "E9 extension: AUROC per corruption and severity 1-8",
            note,
            severity,
        )
        _write(
            f"{p}e09_ext_quality_limits",
            f"E9 extension: quality limits of the final model ({final}) over severities 1-8",
            f"Highest severity s such that pooled AUROC >= {cfg.quality_auroc} at every severity "
            "1..s (ADR-023); 8 = no failure up to the strongest tested level. " + note,
            quality_limits(severity, final, float(cfg.quality_auroc)),
        )
        return 0

    runs = _runs(p, RELIABILITY_FILE)
    df = rel.load(runs)
    base = (
        f"Fold models of the five comparison models (ADR-021), {len(runs)} runs; "
        "`reliability_predictions.csv` from the Phase 5 prediction-only pass (ADR-026). "
    )
    if args.exp == "e10":
        _write(
            f"{p}e10_calibration",
            "E10: calibration before / after temperature scaling",
            base
            + "One temperature per fold model, fitted on its cal images (NLL, LBFGS); T = 1 when "
            "every cal logit already has the correct sign (no finite optimum, E10.md). Pooled over "
            "the held-out folds (each run calibrated, then seed-averaged per image); ECE with 15 "
            f"equal-width top-label bins. Paired 95% bootstrap CIs of after - before ({nb} "
            "resamples, seed 0). Temperature: mean ± sd over the fold models where it was fitted.",
            rel.calibration_table(df, nb),
        )
        rel.reliability_diagram_data(df).to_csv(
            TABLES / f"{p}e10_reliability_bins.csv", index=False, lineterminator="\n"
        )
        selective, curves = rel.selective_table(df)
        _write(
            f"{p}e10_selective",
            "E10: selective prediction, single fold model vs 3-seed ensemble",
            base
            + "Calibrated probabilities, prediction at 0.5, confidence max(p, 1 - p). AURC per "
            "fold model (single, mean ± sd over 15) and per fold for the seed-averaged ensemble "
            "(mean ± sd over 5). MC dropout not run (ADR-025).",
            selective,
        )
        curves.to_csv(TABLES / f"{p}e10_risk_coverage.csv", index=False, lineterminator="\n")
        per_run = rel.conformal_runs(df)
        _write(
            f"{p}e10_conformal",
            "E10: split conformal prediction",
            base + "Quantiles from each fold model's cal images, evaluated on its held-out fold; "
            "calibrated probabilities. Mean ± sd over fold models. Abstention = set of size 2.",
            rel.conformal_table(per_run),
        )
        score, mode, met, summary = rel.choose_conformal(per_run, final)
        _write(
            f"{p}e10_conformal_choice",
            f"E10: conformal method choice for the final model ({final})",
            "Rule (E10.md): methods whose mean per-class coverage falls at most 2 pp below "
            "1 - alpha for both classes and alpha in {0.05, 0.10} qualify; smallest mean set "
            "size at alpha 0.10 wins; ties LAC, then Mondrian. "
            f"Chosen: {score} / {mode}; criterion met: {met}.",
            summary,
        )
        write_json(
            choice_file, {"config": final, "score": score, "mode": mode, "criterion_met": met}
        )
        return 0

    choice = json.loads(choice_file.read_text(encoding="utf-8"))
    _write(
        f"{p}e11_ood",
        "E11: OOD detection, near and far",
        base
        + "ID = each fold model's held-out fold; OOD = all near (Grocery Store packages) and far "
        "(DTD, Open Images scenes) images. Higher score = more OOD. Mean ± sd over fold models "
        "(units = 15), or over folds for ensemble disagreement (units = 5). The val threshold "
        "accepts 95% of the fold model's val images.",
        rel.ood_table(df),
    )
    guard, guard_summary = rel.choose_guard(df, final, DATA_DIR)
    _write(
        f"{p}e11_guard_choice",
        f"E11: guard score for the end-to-end system ({final})",
        "Mean OOD AUROC (near and far together) on the select half of the OOD images (ADR-026); "
        f"highest wins, ties go to kNN. Chosen: {guard}.",
        guard_summary,
    )
    _write(
        f"{p}e11_end_to_end",
        f"E11: end-to-end system vs bare classifier ({final})",
        base + "Stream per fold model = its held-out fold + the eval half of every OOD set. Full "
        f"system: guard `{guard}` (val threshold, 95% acceptance) -> temperature -> conformal "
        f"`{choice['score']}` / `{choice['mode']}` from cal; a singleton is issued, any other set "
        "abstains. Bare classifier: val-selected threshold on the raw probability, every image "
        "issued. An issued prediction on an OOD image counts as an error. Abstained and issued are "
        "fractions of the stream; ID/OOD rejected of the ID/OOD images; error on issued and OOD "
        "among issued of the issued predictions. Mean ± sd over fold models.",
        rel.end_to_end_table(df, final, guard, choice["score"], choice["mode"], DATA_DIR),
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
