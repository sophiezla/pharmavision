"""GPU-hour estimate from a timing batch (CLAUDE.md section 12): fold-0/seed-0 time x run count.

Reads the timing batch's job log (wall time per job, including data loading and evaluation) and
each run's metrics.json (epochs, best epoch, training seconds, peak GPU memory); writes
results/tables/{exp}_timing.md.

Usage:
    python scripts/timing_table.py --exp e01 --log <timing job log> --jobs jobs/e01_gpu.txt
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

from pharmachecked.config import REPO_ROOT
from pharmachecked.jobs import read_jobs
from pharmachecked.utils.io import atomic_write_text, read_json
from pharmachecked.utils.run_dir import parse_run_id, slug

LINE = re.compile(r"\] (done|failed) in ([\d.]+) min (.*)$")


def _arm(overrides: list[str]) -> tuple[str, str]:
    values = dict(o.split("=", 1) for o in overrides if "=" in o)
    return slug(values["model"]), slug(values.get("variant", "default"))


def main() -> int:
    """Write the timing table; returns a process exit code."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--exp", required=True)
    parser.add_argument("--log", type=Path, required=True)
    parser.add_argument("--jobs", type=Path, required=True, help="the full job list to estimate")
    args = parser.parse_args()
    args.log, args.jobs = args.log.resolve(), args.jobs.resolve()
    wall: dict[tuple[str, str], float] = {}
    for line in args.log.read_text(encoding="utf-8").splitlines():
        match = LINE.search(line)
        if match and match[1] == "done":
            wall[_arm(match[3].split())] = float(match[2])
    counts = Counter(_arm(job) for job in read_jobs(args.jobs))
    runs = {}
    for folder in (REPO_ROOT / "results" / "runs").glob(f"{args.exp}_*_f0_s0_*"):
        fields = parse_run_id(folder.name)
        runs[(fields["model"], fields["variant"])] = read_json(folder / "metrics.json")
    log_rel = args.log.relative_to(REPO_ROOT).as_posix()
    jobs_rel = args.jobs.relative_to(REPO_ROOT).as_posix()
    lines = [
        f"# {args.exp}: timing batch and GPU-hour estimate",
        "",
        f"Generated by `scripts/timing_table.py` from `{log_rel}` (wall minutes per job, including "
        "data loading and evaluation) and the fold-0/seed-0 run folders. Estimate = wall minutes "
        f"x runs in `{jobs_rel}`.",
        "",
        "| Arm | Wall min (fold 0, seed 0) | Epochs run | Best epoch | Train min | Peak GPU GB | "
        "Runs | Estimated GPU-hours |",
        "|---|---|---|---|---|---|---|---|",
    ]
    total = 0.0
    for arm in sorted(counts):
        m = runs.get(arm, {})
        minutes = wall.get(arm)
        hours = minutes * counts[arm] / 60 if minutes is not None else float("nan")
        total += 0.0 if minutes is None else hours
        peak = m.get("peak_gpu_memory_gb")
        lines.append(
            f"| {arm[0]} / {arm[1]} | {minutes if minutes is not None else 'missing'} | "
            f"{m.get('epochs_run', '-')} | {m.get('best_epoch', '-')} | "
            f"{m.get('train_seconds', float('nan')) / 60:.1f} | "
            f"{f'{peak:.2f}' if peak is not None else '-'} | {counts[arm]} | {hours:.1f} |"
        )
    lines += ["", f"Total estimated GPU-hours: {total:.1f}"]
    out = REPO_ROOT / "results" / "tables" / f"{args.exp}_timing.md"
    atomic_write_text(out, "\n".join(lines) + "\n")
    sys.stdout.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
